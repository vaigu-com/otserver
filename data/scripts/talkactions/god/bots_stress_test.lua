function spawnMonstersAroundCreature(creature, monsterName, radius)
	if not creature then
		return
	end
	if not monsterName then
		return
	end
	radius = radius or 1
	local creaturePos = creature:getPosition()
	IterateBetweenPositions(creaturePos:Moved(-radius, -radius, 0), creaturePos:Moved(radius, radius, 0), function(context)
		local pos = context.pos
		local tile = Tile(pos)
		if not tile then
			return
		end
		Game.createMonster(monsterName, pos)
	end)
end

