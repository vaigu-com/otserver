local signLook = Look()
function signLook.onLook(player, sign, fromPosition, target, toPosition)
	local text = sign:getAttribute(ITEM_ATTRIBUTE_TEXT) or ""

	local translatedMessage = player:Localizer(LOCALIZERS.DesertQuestOne):Get(text)
	player:sendTextMessage(MESSAGE_LOOK, translatedMessage)

	return DONT_SHOW_ONLOOK
end
for _, id in pairs(signIds) do
	signLook:id(id)
end
